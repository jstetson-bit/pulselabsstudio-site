#!/usr/bin/env python3
"""Builds engine/src/25_formats.js (the per-format catalogs EOD Classic checks maps against)
from the feature-set tables in the Boom Standards spec repo (github.com/elf-alchemist/boom-standards).
Usage: python3 EOD/tools/gen_formats.py /path/to/boom-standards
Only the facts are taken (numbers, triggers, names); the descriptions are rebuilt here."""
import sys, os, re, json
root = sys.argv[1]
LEVELS = [('vanilla', '01_vanilla'), ('boom', '02_boom'), ('mbf', '03_mbf'), ('mbf21', '04_mbf21'), ('id24', '05_id24')]
def sections(text):
    out, cur = {}, None
    for ln in text.splitlines():
        m = re.match(r'^#+\s*(.+?)>?\s*$', ln)
        if m: cur = m.group(1).strip().lower(); out.setdefault(cur, []); continue
        if cur and ln.startswith('|') and not re.match(r'^\|[-\s|]+\|$', ln):
            cells = [c.strip() for c in ln.strip().strip('|').split('|')]
            out[cur].append(cells)
    return {k: v[1:] for k, v in out.items() if v}  # drop header row
def words(s):  # "RaiseFloorToNearest" -> "Raise floor to nearest"
    s = re.sub(r'(?<=[a-z0-9])(?=[A-Z])', ' ', s).strip(); return s[:1].upper() + s[1:].lower() if s else s
cat = {}
for key, d in LEVELS:
    sec = sections(open(os.path.join(root, 'spec', d, 'mapping.md'), encoding='utf-8').read())
    lv = {'lines': {}, 'sectors': {}, 'lineFlags': {}, 'thingFlags': {}, 'things': {}, 'genSector': {}}
    for name, rows in sec.items():
        for r in rows:
            if not r or r[0] in ('-', ''): continue
            if name.startswith('line specials'):
                try: n = int(r[0])
                except ValueError: continue
                trig = r[1]
                if len(r) >= 5 and r[4] not in ('.', '-', ''): desc = r[4]
                elif len(r) >= 4: desc = (words(r[2]) + (' (' + words(r[3]) + ')' if r[3] and r[3] not in ('0',) and not r[3].isdigit() else (' ' + r[3] if r[3].isdigit() else ''))).strip()
                else: desc = r[2] if len(r) > 2 else ''
                lv['lines'][n] = [trig, desc.rstrip('.')]
            elif name.startswith('sector specials'):
                try: n = int(r[0])
                except ValueError: continue
                if r[1] not in ('-',): lv['sectors'][n] = r[1].rstrip('.')
            elif name.startswith('line flags'):
                lv['lineFlags'][int(r[1], 16)] = r[2].rstrip('.')
            elif name.startswith('thing spawn flags'):
                lv['thingFlags'][int(r[1], 16)] = r[2].rstrip('.')
            elif name.startswith('generalized sector'):
                try: lv['genSector'][int(r[1], 16)] = r[2]
                except ValueError: pass
            elif name.startswith('things'):
                try: ed = int(r[1])
                except ValueError: continue
                if ed != -1: lv['things'][ed] = r[2]
    cat[key] = lv
js = ('/* ================= FORMAT CATALOGS (generated by tools/gen_formats.py from the Boom Standards tables) =================\n'
      '   Each level adds to the ones before it: vanilla < boom < mbf < mbf21 < id24. */\n'
      'const FMT_CAT = ' + json.dumps(cat, separators=(',', ':')) + ';\n')
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'engine', 'src', '25_formats.js')
open(out, 'w', encoding='utf-8').write(js)
print({k: {kk: len(vv) for kk, vv in v.items()} for k, v in cat.items()})
